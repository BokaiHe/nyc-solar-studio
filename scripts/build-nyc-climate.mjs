// Builds src/lib/solar/nyc-climate.ts from the PVGIS typical meteorological
// year (TMY) for New York City: hourly beam, diffuse and global irradiance
// and air temperature, averaged by month and UTC hour (12 × 24 values each).
// Usage: node scripts/build-nyc-climate.mjs [path/to/pvgis-tmy.json]
import { readFile, writeFile } from 'node:fs/promises';

const LATITUDE = 40.7128;
const LONGITUDE = -74.006;
const PVGIS_URL = `https://re.jrc.ec.europa.eu/api/v5_3/tmy?lat=${LATITUDE}&lon=${LONGITUDE}&outputformat=json`;
const OUTPUT = new URL('../src/lib/solar/nyc-climate.ts', import.meta.url);

const source = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], 'utf8'))
  : await (await fetch(PVGIS_URL)).json();

const hourly = source.outputs.tmy_hourly;
if (hourly.length !== 8760) throw new Error(`Expected 8760 hourly rows, got ${hourly.length}`);

const sums = Array.from({ length: 12 }, () => Array.from({ length: 24 }, () => ({ dni: 0, dhi: 0, ghi: 0, temp: 0, count: 0 })));
const days = new Array(12).fill(0);
for (const row of hourly) {
  // time(UTC) looks like 20060101:1200; the TMY mixes years, so use month, day and hour only.
  const stamp = row['time(UTC)'];
  const month = Number(stamp.slice(4, 6)) - 1;
  const hour = Number(stamp.slice(9, 11));
  const cell = sums[month][hour];
  cell.dni += row['Gb(n)'];
  cell.dhi += row['Gd(h)'];
  cell.ghi += row['G(h)'];
  cell.temp += row.T2m;
  cell.count += 1;
  if (hour === 0) days[month] += 1;
}

const round = (value, digits) => Number(value.toFixed(digits));
const table = (key, digits) => sums.map((month) => month.map((cell) => round(cell[key] / cell.count, digits)));

const file = `// Generated by scripts/build-nyc-climate.mjs; do not edit by hand.
// Source: ${source.inputs.meteo_data.radiation_db} typical meteorological year
// (${source.inputs.meteo_data.year_min}–${source.inputs.meteo_data.year_max}) at ${LATITUDE}, ${LONGITUDE},
// European Commission Joint Research Centre. Values are means by month and UTC hour;
// irradiance in W/m², temperature in °C.

export const NYC_CLIMATE = {
  source: '${source.inputs.meteo_data.radiation_db} TMY ${source.inputs.meteo_data.year_min}–${source.inputs.meteo_data.year_max}',
  daysInMonth: ${JSON.stringify(days)},
  // Beam irradiance on a plane normal to the sun.
  dni: ${JSON.stringify(table('dni', 1))},
  // Diffuse irradiance on the horizontal plane.
  dhi: ${JSON.stringify(table('dhi', 1))},
  // Global irradiance on the horizontal plane.
  ghi: ${JSON.stringify(table('ghi', 1))},
  airTemperature: ${JSON.stringify(table('temp', 1))},
} as const;
`;
await writeFile(OUTPUT, file);
const annualGhi = sums.reduce((total, month, index) => total + month.reduce((sum, cell) => sum + cell.ghi / cell.count, 0) * days[index], 0) / 1000;
console.log(`Wrote ${OUTPUT.pathname}; annual GHI ${annualGhi.toFixed(0)} kWh/m², days ${days.reduce((a, b) => a + b)}`);
